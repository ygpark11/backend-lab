package com.pstracker.catalog_service.catalog.scheduler;

import com.pstracker.catalog_service.ai.service.AiService;
import com.pstracker.catalog_service.catalog.domain.Game;
import com.pstracker.catalog_service.catalog.repository.GameRepository;
import com.pstracker.catalog_service.catalog.service.GameReadService;
import com.pstracker.catalog_service.search.GameSearchIndexService;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.time.LocalDate;
import java.util.List;

import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.BDDMockito.given;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.times;
import static org.mockito.Mockito.verify;

@ExtendWith(MockitoExtension.class)
class AiDescriptionSchedulerTest {

    @Mock
    private GameRepository gameRepository;

    @Mock
    private AiService aiService;

    @Mock
    private GameReadService gameReadService;

    @Mock
    private GameSearchIndexService gameSearchIndexService;

    @Test
    @DisplayName("AI 응답이 연속 3회 비어 있으면 무한 루프 없이 배치를 중단한다")
    void autoGenerateDescriptions_stopsAfterMaxConsecutiveFailures() {
        AiDescriptionScheduler scheduler = new AiDescriptionScheduler(
                gameRepository, aiService, gameReadService, gameSearchIndexService) {
            @Override
            protected boolean sleepMillis(long millis) {
                return true;
            }
        };

        Game game = Game.create("PS-001", "테스트 게임", "Test Game", "Publisher", "img", "Full Data Crawler", LocalDate.now());
        given(gameRepository.findTop5NeedingAiUpdate(anyString(), any())).willReturn(List.of(game));
        given(aiService.generateBatchInsights(any())).willReturn(List.of());

        scheduler.autoGenerateDescriptions();

        verify(aiService, times(3)).generateBatchInsights(any());
        verify(gameRepository, times(0)).saveAll(any());
    }

    @Test
    @DisplayName("AI 배치 응답이 정상 수신되면 게임 인사이트를 업데이트·저장하고 상세 캐시 무효화 및 검색 색인을 동기화한다")
    void autoGenerateDescriptions_updatesAndSavesOnSuccess() {
        AiDescriptionScheduler scheduler = new AiDescriptionScheduler(
                gameRepository, aiService, gameReadService, gameSearchIndexService) {
            @Override
            protected boolean sleepMillis(long millis) {
                return true;
            }
        };

        Game game = mock(Game.class);
        given(game.getId()).willReturn(1L);
        given(gameRepository.findTop5NeedingAiUpdate(anyString(), any()))
                .willReturn(List.of(game))
                .willReturn(List.of());
        given(aiService.generateBatchInsights(List.of(game))).willReturn(
                List.of(new AiService.AiInsightDto(1L, "요약", List.of("#액션"), List.of("테겜")))
        );

        scheduler.autoGenerateDescriptions();

        verify(game).updateAiInsights("요약", List.of("#액션"));
        verify(game).updateSearchKeywords(List.of("테겜"));
        verify(gameRepository, times(1)).saveAll(List.of(game));
        verify(gameReadService, times(1)).evictGameDetailCache(1L);
        verify(gameSearchIndexService, times(1)).syncGames(List.of(game));
    }
}
